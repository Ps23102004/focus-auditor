"""Findings -> frozen live-adb pytest files, plus the runtime those tests call.
The generated file holds only frozen data; assertions live here so a fix to the checker is one edit."""
import json, os, re, sys

from .adb import Adb
from .crawl import KEYS, LiveDevice
from .tree import effective_label

HEADER = '''"""GENERATED by fa.testgen from report {run_id}. Frozen data; do not hand-edit.
Finding {fid} ({kind}). Live adb test: FAILS while the defect exists, PASSES once fixed."""
import json

import pytest
from fa import testgen

DATA = json.loads({data})


@pytest.mark.device
def test_{fid}():
    testgen.check(DATA)
'''


def _data(report, f):
    d = {"finding_id": f["id"], "kind": f["kind"], "node_id": f["node_id"], "bounds": f["bounds"],
         "keys": f["witness"].get("keys", []), "pkg": report["meta"]["app"],
         "activity": report["meta"].get("activity") or ".MainActivity"}
    ev = f["evidence"]
    nodes = {n["id"]: n for n in report.get("nodes", [])}

    def geo(nid):  # position identity: survives fixes that add/remove nodes and shift tree positions
        n = nodes.get(nid)
        return [n["cls"], [v // 8 for v in n["bounds"]]] if n else None

    d["target_geo"] = [ev.get("cls") or "android.view.View", [v // 8 for v in f["bounds"]]]
    if f["kind"] == "TRAP":
        d.update(region=ev["region"], region_edges=ev["region_edges"], entry_geo=geo(f["node_id"]),
                 region_geo=[geo(i) for i in ev["region"]],
                 edges_geo=[[geo(a), k, geo(b)] for a, k, b in ev["region_edges"]])
    elif f["kind"] == "DUPLICATE_LABEL":
        d.update(label=ev["label"], min_group=3)
    return d


_ID = re.compile(r"^[0-9a-f]{6,16}$")
_KINDS = {"TRAP", "MISSING_LABEL", "DUPLICATE_LABEL"}
_PKG = re.compile(r"^[A-Za-z][\w]*(\.[A-Za-z][\w]*)+$")
_ACT = re.compile(r"^\.?[A-Za-z_][\w.$]*$")
_KEYS = {"UP", "DOWN", "LEFT", "RIGHT", "CENTER", "BACK"}


def _check_target(pkg, activity, keys):
    if not _PKG.match(str(pkg)) or not _ACT.match(str(activity)):
        raise ValueError(f"refusing target {pkg!r}/{activity!r}")
    bad = [k for k in keys if k not in _KEYS]
    if bad:
        raise ValueError(f"refusing witness keys {bad!r}")


def _check_safe(report):
    """Reports can be edited or come from untrusted runs: ids/kinds end up in file names, Python identifiers and
    docstrings, so only accept the exact shapes the engine produces. Everything else goes through json + repr."""
    run_id = str(report["meta"]["run_id"])
    if not _ID.match(run_id):
        raise ValueError(f"refusing report: bad run_id {run_id!r}")
    for f in report["findings"]:
        if not _ID.match(str(f["id"])) or f["kind"] not in _KINDS:
            raise ValueError(f"refusing report: bad finding id/kind {f.get('id')!r}/{f.get('kind')!r}")
        _check_target(report["meta"]["app"], report["meta"].get("activity") or ".MainActivity",
                      (f.get("witness") or {}).get("keys", []))


def generate_tests(report, out_dir="tests_generated"):
    _check_safe(report)
    os.makedirs(out_dir, exist_ok=True)
    for old in os.listdir(out_dir):
        if old.startswith("test_") and old.endswith(".py"):
            os.remove(os.path.join(out_dir, old))
    paths = []
    for f in report["findings"]:
        if not (f.get("witness") or {}).get("keys"):
            # no recorded key path reaches it (e.g. found only in the scroll pass): a replay test could never pass
            print(f"no test for {f['id']} ({f['kind']}): no recorded key path reaches it", file=sys.stderr)
            continue
        p = os.path.join(out_dir, f"test_{f['id']}.py")
        with open(p, "w") as fh:
            fh.write(HEADER.format(run_id=report["meta"]["run_id"], fid=f["id"], kind=f["kind"],
                                   data=repr(json.dumps(_data(report, f), sort_keys=True))))
        paths.append(p)
    return paths


# ---------------- runtime used by generated tests ----------------
def _replay(dev, keys):
    dev.cold_start()
    for k in keys:
        dev.press(k)
    return dev.read()


def _in_app(d, snap):
    """A screen of another package (launcher after a crash or exit) is never evidence that a defect is fixed."""
    foc = snap.focused() if snap is not None else None
    if snap is not None and (snap.package != d["pkg"] or (foc is not None and foc.package and foc.package != d["pkg"])):
        _fail(d, f"the app is no longer in front (saw {snap.package!r}, expected {d['pkg']!r}): leaving or crashing is not a fix")


def _fail(d, msg):
    raise AssertionError(f"[{d['kind']} {d['finding_id']}] {msg}")


def check(d, dev=None):
    _check_target(d["pkg"], d["activity"], d.get("keys", []))  # generated files are editable: re-check before adb
    dev = dev or LiveDevice(Adb(), d["pkg"], d["activity"])
    {"TRAP": _check_trap, "MISSING_LABEL": _check_label, "DUPLICATE_LABEL": _check_dup}[d["kind"]](dev, d)


def _gk(n):
    return (n.cls, tuple(v // 8 for v in n.bounds))


def _find_geo(snap, key):
    want = (key[0], tuple(key[1]))
    cands = [n for n in snap.nodes if _gk(n) == want]
    return next((n for n in cands if n.focusable), cands[0] if cands else None)


def _check_label(dev, d):
    snap = _replay(dev, d["keys"])
    if snap is None:
        _fail(d, f"could not read the screen after replaying {d['keys']}")
    _in_app(d, snap)
    node = _find_geo(snap, d["target_geo"])
    if node is None:
        _fail(d, f"no control at {d['bounds']} after replaying {d['keys']}: it was removed or moved (a deleted control does not pass)")
    if not node.focusable:
        _fail(d, f"the control at {d['bounds']} is no longer focusable: a name on something the remote cannot reach does not pass")
    label = effective_label(node, snap)
    if not label:
        _fail(d, f"node {d['node_id']} at {d['bounds']} still exposes no accessible name")
    print(f"ok: node {d['node_id']} now named {label!r}")


def _check_dup(dev, d):
    snap = _replay(dev, d["keys"])
    if snap is None:
        _fail(d, f"could not read the screen after replaying {d['keys']}")
    _in_app(d, snap)
    target = _find_geo(snap, d["target_geo"])
    if target is None:
        _fail(d, f"no control at {d['bounds']} after replaying {d['keys']}: it was removed or moved")
    if not target.focusable:
        _fail(d, f"the control at {d['bounds']} is no longer focusable")
    same = [n for n in snap.focusables() if effective_label(n, snap) == d["label"]]
    if len(same) >= d["min_group"]:
        _fail(d, f"{len(same)} focusables still share the name {d['label']!r}")
    new = effective_label(target, snap)
    if not new:  # erasing the names is not a fix: the group went from "same name" to "no name"
        _fail(d, f"the control at {d['bounds']} now exposes no accessible name at all")
    # renaming the whole group to one new shared name just moves the defect
    moved = [n for n in snap.focusables() if effective_label(n, snap) == new] if new else []
    if len(moved) >= d["min_group"]:
        _fail(d, f"the group was renamed to {new!r} but {len(moved)} focusables now share that name")
    print(f"ok: only {len(same)} focusable(s) named {d['label']!r}")


def _check_trap(dev, d):
    def key(x):
        return (x[0], tuple(x[1]))

    region = {key(x) for x in d["region_geo"] if x}
    out = {}
    for a, k, b in d["edges_geo"]:
        if a and b:
            out.setdefault(key(a), {})[k] = key(b)

    def inner_path(src, dst):  # key path using only recorded edges inside the region
        seen, q = {src}, [(src, [])]
        while q:
            n, p = q.pop(0)
            if n == dst:
                return p
            for k in KEYS:
                t = out.get(n, {}).get(k)
                if t in region and t not in seen:
                    seen.add(t)
                    q.append((t, p + [k]))
        return None

    entry = key(d["entry_geo"])
    snap = _replay(dev, d["keys"])
    if snap is not None:
        _in_app(d, snap)
    f = snap.focused() if snap else None
    if f is None or _gk(f) != entry:
        _fail(d, f"witness {d['keys']} no longer reaches the region entry at {entry[1]} (focus={_gk(f)[1] if f else None}); the control moved or the focus path changed")
    for member in sorted(region):
        p = inner_path(entry, member)
        if p is None:
            continue
        if p:
            _replay(dev, d["keys"] + p)
        for k in KEYS:
            dev.press(k)
            snap = dev.read()
            f = snap.focused() if snap else None
            if f is None:
                _fail(d, f"no readable focus after {k} from {member[1]}")
            _in_app(d, snap)
            if _gk(f) not in region:
                print(f"ok: {k} from {member[1]} leaves the region (-> {_gk(f)[1]})")
                return
            if _gk(f) != member:  # moved inside the region; go back to the member for the next key
                _replay(dev, d["keys"] + p)
    _fail(d, f"focus never leaves the region of {len(region)} control(s): UP/DOWN/LEFT/RIGHT all stay inside")
